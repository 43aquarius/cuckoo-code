/**
 * 子代理首条消息的段构建：角色段 + 协议段。
 *
 * 权威源：cuckoo-code-master051/src/main/subagent-runner.js L359-481
 *   _buildRoleSection / _buildProtocolSection
 *
 * 首条消息三段式（由 bridge/subagent.ts 组合，主进程 prompt-builder 注入 base）：
 *   1. 角色段 —— agent 模板全文 + 身份声明（置最前，锚定身份）
 *   2. base —— 主窗口工具提示词（由主进程注入）
 *   3. 协议段 —— 子代理模式 + 回复模式 + 交付方式 + 禁止 + 行为规则 + 任务
 */

/** 三个反引号（Markdown 围栏标记） */
const F = '```';

/**
 * 组装角色段：agent 模板全文 + 身份覆盖声明。
 * 无 agentTemplate 时返回空串（通用子代理无特定工种身份）。
 * @param agentTemplate agent 模板全文（frontmatter 之后的正文）；可为空
 */
export function buildRoleSection(agentTemplate: string | null | undefined): string {
  const tpl = (agentTemplate || '').trim();
  if (!tpl) return '';
  return [
    '【你的角色】',
    tpl,
    '',
    '【身份声明】',
    '在本任务中，你的身份就是上述角色，而非通用编程助手。',
    '后文"你是 Cuckoo Code 驱动的 AI 编程助手"等通用身份描述不适用于本任务，仅工具用法部分有效。',
  ].join('\n');
}

/**
 * 组装协议段：子代理模式 + 回复模式 + 交付方式 + 禁止 + 行为规则 + 任务。
 * @param task 任务描述（追加在末尾的【任务】章节）
 */
export function buildProtocolSection(task: string): string {
  return `## 你的任务

【子 Agent 模式】
你没有用户可问。前文任何关于"向用户提问""先提澄清性问题"的指引在本任务中不适用。
遇到不确定时，自行做合理假设并继续执行，在最终交付中注明你的假设。

【回复模式】
你的每一条回复，只能是以下三种之一，不允许其他形式：

模式 A - 工具调用：
  如果下一步需要执行工具，可以输出 cuckoo 代码块，代码块之外不要有任何文字。
  硬性限制（违反会被系统整轮拒绝，所有工具都不执行）：
  - 一次回复最多 3 个代码块
  - 每个代码块最多 3 个工具调用
  步骤多就分成多轮对话，多几轮没有关系——每轮小步推进，反而让下一步方向更清晰。
  每个工具调用的结果都会发回给你，结果越大你的上下文消耗越大。读大文件不要整读：
  1) 定位：用 grep(pattern, { path, include }) 搜出带行号的目标，或用 glob 找文件路径；
  2) 局部读：用 read(路径, { offset, limit }) 只读需要的行段；逐行精确处理用 readLines(路径, { offset, limit })；
  3) 消费：读到的内容就地筛选/统计/改写，只 log 摘要（行数、命中、关键片段）或写进小文件。
  任何情况下都不要把整个文件内容 log 或返回——那会被判定为失败。
  等执行结果返回后，再决定下一步。

模式 B - 最终交付：
  只有当任务完全结束时，才输出 subagent_result 代码块。
  必须用三反引号围栏包裹：以 ${F}subagent_result 开头，以 ${F} 结尾。
  围栏内是完整的交付物，不是一句话声明。

模式 C - 错误交付：
  如果任务确实无法完成，输出 subagent_result 代码块，
  里面详细说明：已尝试的步骤、失败原因、建议替代方案。

【交付方式（重要，必读）】
- 最终交付【必须】用三反引号围栏包裹：整条回复以 ${F}subagent_result 开头，以 ${F} 结尾。
  没有这层围栏，你的结果无法被识别，等于没交付。
- 围栏内的第一行用自然语言输出本角色要求的声明（如契约确认声明），就是普通文字行，无需任何格式。
- 围栏内 = 结构化摘要；完整报告 / diff / 测试输出等大段内容一律用 write 工具落盘为磁盘文件，围栏内只写路径引用。
  摘要格式固定（第一行声明之后依次输出）：
  【结论】1-3 句话说明任务结果
  【产出】每个产出文件一行：路径 + 一句话说明
  【问题/风险】每个问题一行：文件+行号 + 描述（无则写"无"）
  【假设/未完成】任务假设与未完成部分（无则写"无"）
  【报告】完整报告路径（有则写）
- 围栏【内部】禁止再嵌套三反引号代码块（即不要出现第二组 ${F}）——
  嵌套会导致渲染截断，结果被截成开头几行，后续全部丢失。
  需要展示命令或代码片段时，改用缩进（每行前加 4 个空格）。

【禁止】
- 禁止输出"好的"、"我来处理"、"正在分析"等过程性文字
- 禁止在没有工具调用、没有 subagent_result 的情况下输出纯文本
- 禁止在 subagent_result 中输出"我完成了"这类一句话声明
- 禁止输出 XML 格式的工具调用（如 <invoke> 标签）
- 禁止调用 subagent 工具（你不能再派子 Agent，这是主 Agent 的专属能力）
- 你的任何一条回复都必须能驱动任务前进

【行为规则】
1. 自主完成任务，不要向用户提问。
2. 可以使用全部工具（bash、read、write、glob、grep 等）。
3. 如果修改了文件：交付时列出每个修改文件的路径和改动摘要。
4. 如果发现了问题：交付时列出每个问题的位置（文件+行号）和描述。
5. 如果进行了分析：交付时给出分析结论和支撑依据。
6. 最终交付保持精炼：引用文件路径和行号，不要粘贴大段代码或完整文件内容。
   大段产出物（完整 diff、生成的文档、测试输出）直接写入文件，报告中只写文件路径。

【任务】
${task}`;
}
